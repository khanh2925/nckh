-- Quy trình (hành trình nhiều bước): chủ địa điểm định nghĩa chuỗi bước, khách được dẫn lần lượt qua từng bước.
-- Đặc tả: docs/DAC_TA_QUY_TRINH.md. Câu hỏi đầu và các bước luôn đọc/ghi cùng quy trình, nên lưu JSONB ngay trong dòng:
--   questions: [{ "id": "q1", "text": "Bạn đã check-in trực tuyến chưa?" }]                      (tối đa 3, có/không)
--   steps:     [{ "title", "instruction", "targetLocationId" | "targetType" (mã loại), "optional",
--                 "skipIf": [{ "questionId", "answer" }], "dwellMinutes", "mustConfirm" }]           (2–15 bước khi công khai)
CREATE TABLE IF NOT EXISTS journeys (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_id    BIGINT NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
    name        TEXT NOT NULL CHECK (btrim(name) <> ''),
    description TEXT,
    icon        TEXT,
    status      TEXT NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'PUBLISHED')),
    sort_order  INTEGER NOT NULL DEFAULT 0,
    questions   JSONB NOT NULL DEFAULT '[]',
    steps       JSONB NOT NULL DEFAULT '[]',
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS journeys_venue_idx ON journeys(venue_id);
