-- 1. Bảng mới không phụ thuộc dữ liệu cũ ------------------------------------------
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         TEXT NOT NULL UNIQUE CHECK (btrim(email) <> ''),
    password_hash TEXT NOT NULL,
    full_name     TEXT NOT NULL,
    role          TEXT NOT NULL CHECK (role IN ('VENUE_ADMIN', 'SYSTEM_ADMIN')),
    status        TEXT NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'ACTIVE', 'LOCKED')),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE venues (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug        TEXT NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    name        TEXT NOT NULL CHECK (btrim(name) <> ''),
    kind        TEXT NOT NULL DEFAULT 'other'
                CHECK (kind IN ('airport', 'hospital', 'school', 'mall', 'park', 'office', 'other')),
    description TEXT,
    center_lat  DOUBLE PRECISION,
    center_lng  DOUBLE PRECISION,
    outline     JSONB,
    status      TEXT NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'PUBLISHED', 'HIDDEN')),
    owner_id    BIGINT REFERENCES users(id),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX venues_owner_idx ON venues(owner_id);
CREATE INDEX venues_status_idx ON venues(status);

CREATE TABLE type_templates (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind       TEXT NOT NULL DEFAULT 'all',
    code       TEXT NOT NULL CHECK (code ~ '^[a-z0-9_]+$'),
    name       TEXT NOT NULL,
    icon       TEXT,
    color      TEXT,
    group_name TEXT,
    sort_order INTEGER NOT NULL DEFAULT 0,
    UNIQUE (kind, code)
);

