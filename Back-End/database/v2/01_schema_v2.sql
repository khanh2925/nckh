-- =====================================================================
-- Indoor Map Platform – schema v2 (nhiều địa điểm / multi-venue)
-- Chạy trên database TRỐNG. Database đã có dữ liệu sân bay (schema v1)
-- thì chạy 02_migrate_from_v1.sql thay vì file này.
--
-- Mô hình: users → venues → buildings → floors → { zones, locations, walkway_nodes }
--          venues → { location_types, facilities }
--          walkway_nodes ↔ walkway_edges
-- Toạ độ: x, y = pixel trên bản vẽ mặt bằng của tầng; lat, lng = WGS84.
-- =====================================================================
SET search_path TO public;
BEGIN;

-- Tài khoản: VENUE_ADMIN (chủ địa điểm) và SYSTEM_ADMIN (quản trị hệ thống)
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         TEXT NOT NULL UNIQUE CHECK (btrim(email) <> ''),
    password_hash TEXT NOT NULL,
    full_name     TEXT NOT NULL,
    role          TEXT NOT NULL CHECK (role IN ('VENUE_ADMIN', 'SYSTEM_ADMIN')),
    -- PENDING: mới đăng ký, chờ duyệt; ACTIVE: dùng được; LOCKED: bị khoá
    status        TEXT NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'ACTIVE', 'LOCKED')),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Địa điểm (sân bay, bệnh viện, trường, công viên...)
CREATE TABLE venues (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug        TEXT NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    name        TEXT NOT NULL CHECK (btrim(name) <> ''),
    kind        TEXT NOT NULL DEFAULT 'other'
                CHECK (kind IN ('airport', 'hospital', 'school', 'mall', 'park', 'office', 'other')),
    description TEXT,
    center_lat  DOUBLE PRECISION,
    center_lng  DOUBLE PRECISION,
    -- Vùng bao trên bản đồ nền: JSON [[lat, lng], ...]
    outline     JSONB,
    -- DRAFT: đang dựng; PUBLISHED: khách xem được; HIDDEN: quản trị hệ thống ẩn
    status      TEXT NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'PUBLISHED', 'HIDDEN')),
    owner_id    BIGINT REFERENCES users(id),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX venues_owner_idx ON venues(owner_id);
CREATE INDEX venues_status_idx ON venues(status);

-- Toà nhà / nhà ga / khu trong một địa điểm
CREATE TABLE buildings (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_id   BIGINT NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
    code       TEXT NOT NULL CHECK (btrim(code) <> ''),
    name       TEXT NOT NULL,
    center_lat DOUBLE PRECISION,
    center_lng DOUBLE PRECISION,
    outline    JSONB,
    sort_order INTEGER NOT NULL DEFAULT 0,
    UNIQUE (venue_id, code)
);

-- Tầng: mặt bằng (SVG) + tham số căn chỉnh pixel ↔ lat/lng (phép chiếu affine, xem Front-End/src/utils/projection.js)
CREATE TABLE floors (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    building_id BIGINT NOT NULL REFERENCES buildings(id) ON DELETE CASCADE,
    level       INTEGER NOT NULL,
    name        TEXT NOT NULL,
    -- Bản vẽ mặt bằng: nội dung SVG (phần bên trong <svg>) hoặc URL ảnh trên object storage
    plan_svg    TEXT,
    plan_image_url TEXT,
    plan_width  DOUBLE PRECISION,
    plan_height DOUBLE PRECISION,
    -- Hai điểm mốc: (anchor_x, anchor_y) trên bản vẽ ứng với (anchor_lat, anchor_lng) thực tế, tương tự cho end
    anchor_x    DOUBLE PRECISION, anchor_y DOUBLE PRECISION, anchor_lat DOUBLE PRECISION, anchor_lng DOUBLE PRECISION,
    end_x       DOUBLE PRECISION, end_y    DOUBLE PRECISION, end_lat    DOUBLE PRECISION, end_lng    DOUBLE PRECISION,
    depth_scale DOUBLE PRECISION NOT NULL DEFAULT 1,
    UNIQUE (building_id, level)
);

-- Vùng chức năng trên mặt bằng: polygon JSON [[x, y], ...] (pixel)
CREATE TABLE zones (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    floor_id   BIGINT NOT NULL REFERENCES floors(id) ON DELETE CASCADE,
    name       TEXT NOT NULL CHECK (btrim(name) <> ''),
    color      TEXT,
    polygon    JSONB NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX zones_floor_idx ON zones(floor_id);

-- Loại địa điểm do từng venue tự định nghĩa (gate, checkin cho sân bay; phòng khám cho bệnh viện...)
CREATE TABLE location_types (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_id   BIGINT NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
    code       TEXT NOT NULL CHECK (code ~ '^[a-z0-9_]+$'),
    name       TEXT NOT NULL,
    icon       TEXT,            -- tên icon Bootstrap Icons, ví dụ bi-door-open
    color      TEXT,            -- màu marker, ví dụ #4a4f55
    group_name TEXT,            -- nhóm lọc trên bản đồ: food, service, transport...
    sort_order INTEGER NOT NULL DEFAULT 0,
    UNIQUE (venue_id, code)
);

-- Tiện ích gắn cho địa điểm (Wi-Fi, ổ cắm, xe lăn...), riêng từng venue
CREATE TABLE facilities (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_id BIGINT NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
    name     TEXT NOT NULL CHECK (btrim(name) <> ''),
    UNIQUE (venue_id, name)
);

-- Điểm quan tâm (POI)
CREATE SEQUENCE location_id_seq;
CREATE TABLE locations (
    id              BIGINT PRIMARY KEY DEFAULT nextval('location_id_seq'),
    floor_id        BIGINT NOT NULL REFERENCES floors(id) ON DELETE CASCADE,
    type_id         BIGINT REFERENCES location_types(id) ON DELETE SET NULL,
    name            TEXT NOT NULL CHECK (btrim(name) <> ''),
    x               DOUBLE PRECISION, y   DOUBLE PRECISION,
    lat             DOUBLE PRECISION, lng DOUBLE PRECISION,
    phone           TEXT,
    website         TEXT,
    area            TEXT,
    description     TEXT,
    opening_hours   TEXT,
    image_url       TEXT,
    source_id       BIGINT,
    facilities_known BOOLEAN NOT NULL DEFAULT false,
    CONSTRAINT location_coordinates CHECK ((x IS NOT NULL AND y IS NOT NULL) OR (lat IS NOT NULL AND lng IS NOT NULL))
);
ALTER SEQUENCE location_id_seq OWNED BY locations.id;
COMMENT ON COLUMN locations.x IS 'pixel X trên bản vẽ mặt bằng, không phải kinh độ';
COMMENT ON COLUMN locations.y IS 'pixel Y trên bản vẽ mặt bằng, không phải vĩ độ';
CREATE INDEX locations_floor_idx ON locations(floor_id);
CREATE INDEX locations_type_idx ON locations(type_id);

CREATE TABLE location_facilities (
    location_id BIGINT NOT NULL REFERENCES locations(id) ON DELETE CASCADE,
    facility_id BIGINT NOT NULL REFERENCES facilities(id) ON DELETE CASCADE,
    position    INTEGER NOT NULL CHECK (position >= 0),
    PRIMARY KEY (location_id, facility_id),
    UNIQUE (location_id, position)
);

-- Mạng lối đi (đồ thị): điểm và đoạn. Id điểm do Builder đặt, nên có tiền tố venue để không trùng: "tsn:T1-0-15"
CREATE TABLE walkway_nodes (
    id        TEXT PRIMARY KEY CHECK (btrim(id) <> ''),
    floor_id  BIGINT NOT NULL REFERENCES floors(id) ON DELETE CASCADE,
    lat       DOUBLE PRECISION NOT NULL,
    lng       DOUBLE PRECISION NOT NULL,
    -- 'Thang máy', 'Thang cuốn', 'Thang bộ' khi đổi tầng tại điểm này
    connector TEXT
);
CREATE TABLE walkway_edges (
    from_id TEXT NOT NULL REFERENCES walkway_nodes(id) ON DELETE CASCADE,
    to_id   TEXT NOT NULL REFERENCES walkway_nodes(id) ON DELETE CASCADE,
    PRIMARY KEY (from_id, to_id),
    CHECK (from_id <> to_id)
);
CREATE INDEX walkway_nodes_floor_idx ON walkway_nodes(floor_id);
CREATE INDEX walkway_edges_to_idx ON walkway_edges(to_id);

-- Danh mục mặc định (quản trị hệ thống quản lý): loại địa điểm mẫu theo loại hình venue.
-- kind = 'all' áp dụng cho mọi loại hình. Khi tạo venue mới, các mẫu phù hợp được sao chép sang location_types.
CREATE TABLE type_templates (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind       TEXT NOT NULL DEFAULT 'all',
    code       TEXT NOT NULL CHECK (code ~ '^[a-z0-9_]+$'),
    name       TEXT NOT NULL,
    icon       TEXT,
    color      TEXT,
    group_name TEXT,
    sort_order INTEGER NOT NULL DEFAULT 0,
    UNIQUE (kind, code)
);

COMMIT;
